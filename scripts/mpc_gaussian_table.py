#!/usr/bin/env python3
"""Reproduce the public sigma=1, radius=16, 192-bit inverse-CDF table."""
from decimal import Decimal, localcontext
from fractions import Fraction
from functools import cache
from pathlib import Path
import sys


def table(precision):
    """Return integer CDF boundaries at a specified decimal precision."""
    with localcontext() as ctx:
        ctx.prec = precision
        weights = [(-Decimal(x * x) / 2).exp() for x in range(-16, 17)]
        total = sum(weights)
        cumulative = Decimal(0)
        result = []
        for weight in weights[:-1]:
            cumulative += weight
            result.append(int(cumulative / total * Decimal(2)**192))
        return result



@cache
def exp_interval(exponent):
    """Bound exp(-exponent) by integers scaled by 2^512, using rational arithmetic."""
    scale = 2**512
    z = Fraction(exponent) / 256
    assert 0 <= z < 1
    term = total = Fraction(1)
    upper = None
    # Alternating series, decreasing terms: even partial sum is an upper bound,
    # odd partial sum a lower bound. Then square eight times with directed rounding.
    for k in range(1, 98):
        term *= -z / k
        total += term
        if k == 96:
            upper = total
    lower = total
    lo = (lower.numerator * scale) // lower.denominator
    hi = -((-upper.numerator * scale) // upper.denominator)
    for _ in range(8):
        lo = lo * lo // scale
        hi = (hi * hi + scale - 1) // scale
    return lo, hi


def certify(values):
    """Certify every floor-rounded CDF boundary and the TV bound using integers."""
    bounds = [exp_interval(Fraction(x*x, 2)) for x in range(-16, 17)]
    total_lo = sum(lo for lo, _ in bounds)
    total_hi = sum(hi for _, hi in bounds)
    sum_lo = sum_hi = 0
    for expected, (lo, hi) in zip(values, bounds[:-1]):
        sum_lo += lo
        sum_hi += hi
        assert (sum_lo * 2**192) // total_hi == expected
        assert (sum_hi * 2**192) // total_lo == expected
    tail = Fraction(2 * exp_interval(Fraction(289, 2))[1],
                    2**512 - exp_interval(Fraction(35, 2))[1])
    assert tail + Fraction(32, 2**192) < Fraction(1, 2**186)


def main():
    """Generate or verify checked-in constants and basic approximation bounds."""
    values = table(160)
    assert values == table(240)
    certify(values)
    assert all(0 < a < b < 2**192 for a, b in zip(values, values[1:]))
    # The normalized discrete Gaussian has normalizer >= 1. Its omitted tails
    # are bounded by 2 exp(-17²/2)/(1-exp(-17.5)).
    with localcontext() as ctx:
        ctx.prec = 160
        tail = 2 * (-Decimal(289)/2).exp() / (1-(-Decimal('17.5')).exp())
        assert tail + Decimal(32)/Decimal(2)**192 < Decimal(2)**-186
    lines = ['//! Generated by scripts/mpc_gaussian_table.py; little-endian 192-bit boundaries.',
             '', '/// Inverse-CDF boundaries for values -16 through 15, sigma=1.',
             'pub const CDF: [[u64; 3]; 32] = [']
    for value in values:
        limbs = [(value >> (64*i)) & (2**64-1) for i in range(3)]
        lines.append('    [' + ', '.join(f'0x{x:016x}' for x in limbs) + '],')
    lines.extend(['];', ''])
    text = '\n'.join(lines)
    path = Path(__file__).resolve().parents[1] / 'src/mpc/gaussian/table.rs'
    if '--write' in sys.argv:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text)
    else:
        assert path.read_text() == text, 'CDF constants differ; run with --write'
        print('32 CDF boundaries certified by rational intervals; per-sample TV bound < 2^-186')


if __name__ == '__main__':
    main()
